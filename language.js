function getLanguage() {
  return localStorage.getItem("edenwerbung-language") || "de";
}

function translate(key) {
  const language = getLanguage();
  return translations[language]?.[key] ?? translations.de[key] ?? key;
}

function setLanguage(language) {
  const lang = translations[language] ? language : "de";
  const t = translations[lang];

  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;

    if (t[key] !== undefined) {
      element.textContent = t[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.dataset.i18nPlaceholder;

    if (t[key] !== undefined) {
      element.placeholder = t[key];
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach(element => {
    const key = element.dataset.i18nAlt;

    if (t[key] !== undefined) {
      element.alt = t[key];
    }
  });

  document.querySelectorAll("[data-lang]").forEach(button => {
    const active = button.dataset.lang === lang;

    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  localStorage.setItem("edenwerbung-language", lang);

  document.title = lang === "en"
    ? (document.querySelector("#ad-form") ? "Submit advertisement" : "edenwerbung")
    : (document.querySelector("#ad-form") ? "Werbung einreichen" : "edenwerbung");
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll("[data-lang]").forEach(button => {
    button.addEventListener("click", () => {
      setLanguage(button.dataset.lang);
    });
  });

  setLanguage(getLanguage());
});
